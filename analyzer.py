def analyze_image(image_path, full=False):

    with open(image_path, "rb") as image_file:
        image_data = base64.b64encode(
            image_file.read()
        ).decode("utf-8")

    if full:
        prompt = FULL_PROMPT
    else:
        prompt = SHORT_PROMPT

    response = client.responses.create(
        model="gpt-5.6-luna",
        input=[
            {
                "role": "user",
                "content": [
                    {
                        "type": "input_text",
                        "text": prompt
                    },
                    {
                        "type": "input_image",
                        "image_url": (
                            f"data:image/jpeg;base64,{image_data}"
                        )
                    }
                ]
            }
        ]
    )

    return response.output_text
