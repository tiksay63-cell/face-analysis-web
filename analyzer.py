def analyze_image(image_path, full=False):

    with open(image_path, "rb") as image_file:

        image_data = base64.b64encode(
            image_file.read()
        ).decode("utf-8")

    if full:

        prompt = ANALYSIS_PROMPT + """

Это РАСШИРЕННЫЙ анализ.

Добавь больше конкретики к каждому разделу,
но не делай текст чрезмерно длинным.

В конце обязательно добавь:

💡 ИНДИВИДУАЛЬНЫЕ РЕКОМЕНДАЦИИ

1. ...
2. ...
3. ...
4. ...

Рекомендации должны относиться к визуальной подаче,
а не к изменению анатомии лица.
"""

    else:

        prompt = ANALYSIS_PROMPT + """

Это КРАТКИЙ анализ.

Сохрани только самые заметные наблюдения.
Каждый раздел — максимум 2–3 коротких предложения.
"""

